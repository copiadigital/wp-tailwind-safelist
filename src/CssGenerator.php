namespace CopiaDigital\TailwindSafelist;

/**
 * PHP-based Tailwind CSS generator.
 *
 * Parses Tailwind utility class names (including arbitrary values like
 * `-mt-[20px]`, variants like `md:hover:tw-bg-primary/50`, and the
 * configured class prefix) and emits CSS rules directly. This replaces
 * running `yarn build` on servers that can't run Node.
 *
 * Scope is intentionally pragmatic: it covers the utilities that show
 * up in CMS-authored content (spacing, sizing, layout, flex/grid, color,
 * border, typography, common state variants). Anything not recognised
 * is silently skipped — those classes should already be in the main
 * Tailwind build that ships with the theme.
 */
