    private array $radii;
    private array $pseudoVariants;
    private array $screenVariants;

    /** Class names to skip — already present in the main bundle. */
    private array $excludeClasses;

    public function __construct(array $config = [])
    {
        $this->prefix = (string) ($config['prefix'] ?? '');
        $this->spacing = $this->normaliseMap($config['spacing'] ?? []);
        $this->colors = $this->normaliseMap($config['colors'] ?? []);
        $this->fontSizes = $this->normaliseMap($config['font_sizes'] ?? []);
        $this->radii = $this->normaliseMap($config['radii'] ?? []);
        $this->excludeClasses = $config['exclude_classes'] ?? [];

        $this->screenVariants = $config['screens'] ?? [
            'sm' => '576px',
            'md' => '768px',
            'lg' => '992px',
            'xl' => '1200px',
            '2xl' => '1400px',
        ];

        $this->pseudoVariants = $config['pseudo_variants'] ?? [
            'hover' => ':hover',
            'focus' => ':focus',
            'focus-within' => ':focus-within',
            'focus-visible' => ':focus-visible',
            'active' => ':active',
            'visited' => ':visited',
            'disabled' => ':disabled',
            'checked' => ':checked',
            'first' => ':first-child',
            'last' => ':last-child',
            'odd' => ':nth-child(odd)',
            'even' => ':nth-child(even)',
            'file' => '::file-selector-button',
            'placeholder' => '::placeholder',
            'before' => '::before',
            'after' => '::after',
        ];
    }

    /**
     * Generate a complete CSS document for a list of class names.
     */
    public function generate(array $classes): string
    {
        $base = '';
        $media = []; // "min-width: 768px" => rules string

        $seen = [];
        foreach ($classes as $class) {
            $class = trim($class);
            if ($class === '' || isset($seen[$class])) {
                continue;
            }
            $seen[$class] = true;

            // Skip classes already present in the compiled bundle.
            if (isset($this->excludeClasses[$class])) {
                continue;
            }

            $rule = $this->compileClass($class);
            if ($rule === null) {
                continue;
            }

            if ($rule['media'] !== null) {
                $media[$rule['media']] = ($media[$rule['media']] ?? '') . $rule['css'];
            } else {
                $base .= $rule['css'];
            }
        }

        $css = "/* Generated by wp-tailwind-safelist. Do not edit. */\n";
        $css .= $base;

        uksort($media, fn($a, $b) => $this->extractPx($a) <=> $this->extractPx($b));
        foreach ($media as $query => $rules) {
            $css .= "@media ($query) {\n$rules}\n";
        }

        return $css;
    }

    private function extractPx(string $query): int
    {
        return (int) preg_replace('/\D+/', '', $query);
    }

    /**
     * Compile a single class name into a CSS rule.
     *
     * @return array{css:string, media:?string}|null
     */
    private function compileClass(string $class): ?array
    {
        ['variants' => $variants, 'utility' => $utility] = $this->splitVariants($class);

        $negative = false;
        if (str_starts_with($utility, '-')) {
            $negative = true;
            $utility = substr($utility, 1);
        }

        if ($this->prefix !== '') {
            if (!str_starts_with($utility, $this->prefix)) {
                return null;
            }
            $utility = substr($utility, strlen($this->prefix));
        }

        $declarations = $this->resolveUtility($utility, $negative);
        if ($declarations === null) {
            return null;
        }

        $pseudo = '';
        $media = null;
        foreach ($variants as $variant) {
            if (isset($this->pseudoVariants[$variant])) {
                $pseudo .= $this->pseudoVariants[$variant];
            } elseif (isset($this->screenVariants[$variant])) {
                $media = 'min-width: ' . $this->screenVariants[$variant];
            } else {
                return null;
            }
        }

        $selector = '.' . $this->escapeSelector($class) . $pseudo;
        return ['css' => "$selector { $declarations }\n", 'media' => $media];
    }

    /**
     * Split a class name into ordered variant chain + final utility.
     * Splits on `:` but ignores `:` inside `[...]`.
     *
     * @return array{variants:array<int,string>, utility:string}
     */
    private function splitVariants(string $class): array
    {
        $parts = [];
        $buf = '';
        $depth = 0;
        $len = strlen($class);
        for ($i = 0; $i < $len; $i++) {
            $c = $class[$i];
            if ($c === '[') $depth++;
            elseif ($c === ']') $depth--;
            if ($c === ':' && $depth === 0) {
                $parts[] = $buf;
                $buf = '';
                continue;
            }
            $buf .= $c;
        }
        $parts[] = $buf;
        $utility = array_pop($parts);
        return ['variants' => $parts, 'utility' => $utility];
    }

    private function escapeSelector(string $class): string
    {
        return preg_replace('/([:\/\[\]\(\)#%.\\\\!,])/', '\\\\$1', $class);
    }

    private function resolveUtility(string $utility, bool $negative): ?string
    {
        if (!$negative) {
            $static = $this->staticUtility($utility);
            if ($static !== null) {
                return $static;
            }
        }
        return $this->parameterisedUtility($utility, $negative);
    }

