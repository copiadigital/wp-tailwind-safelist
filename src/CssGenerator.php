    private function parameterisedUtility(string $utility, bool $negative): ?string
    {
        // Margin
        if (preg_match('/^m([trblxy])?-(.+)$/', $utility, $m)) {
            $value = $this->resolveSpacing($m[2], $negative);
            if ($value === null) return null;
            return $this->boxProperty('margin', $m[1] ?? '', $value);
        }
        // Padding (negative invalid)
        if (!$negative && preg_match('/^p([trblxy])?-(.+)$/', $utility, $m)) {
            $value = $this->resolveSpacing($m[2], false);
            if ($value === null) return null;
            return $this->boxProperty('padding', $m[1] ?? '', $value);
        }
        // Inset
        if (preg_match('/^(top|right|bottom|left|inset|inset-x|inset-y)-(.+)$/', $utility, $m)) {
            $value = $this->resolveSpacing($m[2], $negative);
            if ($value === null) return null;
            return $this->insetProperty($m[1], $value);
        }
        // Width / Height / min/max
        if (!$negative && preg_match('/^(w|h|min-w|max-w|min-h|max-h)-(.+)$/', $utility, $m)) {
            $value = $this->resolveSpacing($m[2], false);
            if ($value === null) return null;
            $prop = match ($m[1]) {
                'w' => 'width',
                'h' => 'height',
                'min-w' => 'min-width',
                'max-w' => 'max-width',
                'min-h' => 'min-height',
                'max-h' => 'max-height',
            };
            return "$prop: $value;";
        }
        // size-*
        if (!$negative && preg_match('/^size-(.+)$/', $utility, $m)) {
            $value = $this->resolveSpacing($m[1], false);
            if ($value === null) return null;
            return "width: $value; height: $value;";
        }
        // Gap
        if (!$negative && preg_match('/^gap(-x|-y)?-(.+)$/', $utility, $m)) {
            $value = $this->resolveSpacing($m[2], false);
            if ($value === null) return null;
            return match ($m[1] ?? '') {
                '-x' => "column-gap: $value;",
                '-y' => "row-gap: $value;",
                default => "gap: $value;",
            };
        }
        // Background color
        if (!$negative && preg_match('/^bg-(.+)$/', $utility, $m)) {
            $value = $this->resolveColor($m[1]);
            if ($value === null) return null;
            return "background-color: $value;";
        }
        // Text — size or color
        if (!$negative && preg_match('/^text-(.+)$/', $utility, $m)) {
            $token = $m[1];
            if (isset($this->fontSizes[$token])) {
                return "font-size: {$this->fontSizes[$token]};";
            }
            if (preg_match('/^\[(.+)\]$/', $token, $a)) {
                $v = str_replace('_', ' ', $a[1]);
                if (preg_match('/(px|rem|em|%|vh|vw|ch|ex|pt)$/i', $v)) {
                    return "font-size: $v;";
                }
                return "color: $v;";
            }
            $color = $this->resolveColor($token);
            if ($color !== null) return "color: $color;";
            return null;
        }
        // Numeric font-weight
        if (!$negative && preg_match('/^font-(\d+)$/', $utility, $m)) {
            return "font-weight: {$m[1]};";
        }
        // Leading / tracking
        if (!$negative && preg_match('/^leading-(.+)$/', $utility, $m)) {
            $v = $this->resolveArbitraryOrNumber($m[1]);
            return $v !== null ? "line-height: $v;" : null;
        }
        if (preg_match('/^tracking-(.+)$/', $utility, $m)) {
            $v = $this->resolveArbitraryOrNumber($m[1]);
            if ($v === null) return null;
            return 'letter-spacing: ' . ($negative ? "-$v" : $v) . ';';
        }
        // Border width: border-{n}
        if (!$negative && preg_match('/^border-(\d+)$/', $utility, $m)) {
            return "border-width: {$m[1]}px;";
        }
        if (!$negative && preg_match('/^border-([trbl])-(\d+)$/', $utility, $m)) {
            $side = ['t' => 'top', 'r' => 'right', 'b' => 'bottom', 'l' => 'left'][$m[1]];
            return "border-$side-width: {$m[2]}px;";
        }
        // Border color
        if (!$negative && preg_match('/^border-(.+)$/', $utility, $m)) {
            $color = $this->resolveColor($m[1]);
            if ($color !== null) return "border-color: $color;";
            return null;
        }
        // Rounded with corner + value
        if (!$negative && preg_match('/^rounded-(t|r|b|l|tl|tr|bl|br)-(.+)$/', $utility, $m)) {
            $value = $this->resolveRadius($m[2]);
            if ($value === null) return null;
            return $this->cornerProperty($m[1], $value);
        }
        // Rounded with value only
        if (!$negative && preg_match('/^rounded-(.+)$/', $utility, $m)) {
            // corner-only forms (rounded-t etc.) handled above by static map fallback
            $value = $this->resolveRadius($m[1]);
            if ($value === null) return null;
            return "border-radius: $value;";
        }
        // Opacity
        if (!$negative && preg_match('/^opacity-(\d+)$/', $utility, $m)) {
            return 'opacity: ' . ($m[1] / 100) . ';';
        }
        // Z-index
        if (preg_match('/^z-(.+)$/', $utility, $m)) {
            $v = $this->resolveArbitraryOrNumber($m[1]);
            if ($v === null) return null;
            return 'z-index: ' . ($negative ? "-$v" : $v) . ';';
        }
        // Grid columns / rows
        if (!$negative && preg_match('/^grid-cols-(\d+)$/', $utility, $m)) {
            return "grid-template-columns: repeat({$m[1]}, minmax(0, 1fr));";
        }
        if (!$negative && preg_match('/^grid-cols-\[(.+)\]$/', $utility, $m)) {
            return 'grid-template-columns: ' . str_replace('_', ' ', $m[1]) . ';';
        }
        if (!$negative && preg_match('/^grid-rows-(\d+)$/', $utility, $m)) {
            return "grid-template-rows: repeat({$m[1]}, minmax(0, 1fr));";
        }
        // Span / start / end
        if (!$negative && preg_match('/^col-span-(\d+|full)$/', $utility, $m)) {
            return $m[1] === 'full' ? 'grid-column: 1 / -1;' : "grid-column: span {$m[1]} / span {$m[1]};";
        }
        if (!$negative && preg_match('/^row-span-(\d+|full)$/', $utility, $m)) {
            return $m[1] === 'full' ? 'grid-row: 1 / -1;' : "grid-row: span {$m[1]} / span {$m[1]};";
        }
        if (!$negative && preg_match('/^col-start-(\d+)$/', $utility, $m)) {
            return "grid-column-start: {$m[1]};";
        }
        if (!$negative && preg_match('/^col-end-(\d+)$/', $utility, $m)) {
            return "grid-column-end: {$m[1]};";
        }
        // Order
        if (preg_match('/^order-(\d+)$/', $utility, $m)) {
            return 'order: ' . ($negative ? "-{$m[1]}" : $m[1]) . ';';
        }
        // Aspect
        if (!$negative && preg_match('/^aspect-(.+)$/', $utility, $m)) {
            $map = ['square' => '1 / 1', 'video' => '16 / 9', 'auto' => 'auto'];
            $v = $map[$m[1]] ?? $this->arbitrary($m[1]);
            if ($v === null) return null;
            return "aspect-ratio: $v;";
        }
        // Duration / delay
        if (!$negative && preg_match('/^duration-(\d+)$/', $utility, $m)) {
            return "transition-duration: {$m[1]}ms;";
        }
        if (!$negative && preg_match('/^delay-(\d+)$/', $utility, $m)) {
            return "transition-delay: {$m[1]}ms;";
        }
        // Transforms
        if (preg_match('/^translate-(x|y)-(.+)$/', $utility, $m)) {
            $v = $this->resolveSpacing($m[2], $negative);
            if ($v === null) return null;
            $axis = strtoupper($m[1]);
            return "transform: translate$axis($v);";
        }
        if (preg_match('/^rotate-(.+)$/', $utility, $m)) {
            $v = $this->resolveArbitraryOrNumber($m[1]);
            if ($v === null) return null;
            return 'transform: rotate(' . ($negative ? "-$v" : $v) . 'deg);';
        }
        if (!$negative && preg_match('/^scale-(\d+)$/', $utility, $m)) {
            return 'transform: scale(' . ($m[1] / 100) . ');';
        }

        return null;
    }

    private function boxProperty(string $base, string $side, string $value): string
    {
        return match ($side) {
            '' => "$base: $value;",
            't' => "$base-top: $value;",
            'r' => "$base-right: $value;",
            'b' => "$base-bottom: $value;",
            'l' => "$base-left: $value;",
            'x' => "$base-left: $value; $base-right: $value;",
            'y' => "$base-top: $value; $base-bottom: $value;",
        };
    }

    private function insetProperty(string $key, string $value): string
    {
        return match ($key) {
            'top' => "top: $value;",
            'right' => "right: $value;",
            'bottom' => "bottom: $value;",
            'left' => "left: $value;",
            'inset' => "inset: $value;",
            'inset-x' => "left: $value; right: $value;",
            'inset-y' => "top: $value; bottom: $value;",
        };
    }

    private function cornerProperty(string $corner, string $value): string
    {
        return match ($corner) {
            't' => "border-top-left-radius: $value; border-top-right-radius: $value;",
            'r' => "border-top-right-radius: $value; border-bottom-right-radius: $value;",
            'b' => "border-bottom-left-radius: $value; border-bottom-right-radius: $value;",
            'l' => "border-top-left-radius: $value; border-bottom-left-radius: $value;",
            'tl' => "border-top-left-radius: $value;",
            'tr' => "border-top-right-radius: $value;",
            'bl' => "border-bottom-left-radius: $value;",
            'br' => "border-bottom-right-radius: $value;",
            default => "border-radius: $value;",
        };
    }

    /**
     * Resolve a spacing token: arbitrary, fraction, keyword, theme scale, or default rem.
     */
    private function resolveSpacing(string $token, bool $negative): ?string
    {
        $arb = $this->arbitrary($token);
        if ($arb !== null) {
            return $negative ? $this->negate($arb) : $arb;
        }
        if (preg_match('#^(\d+)/(\d+)$#', $token, $m)) {
            $pct = round(($m[1] / $m[2]) * 100, 6) . '%';
            return $negative ? "-$pct" : $pct;
        }
        $keywords = [
            'auto' => 'auto',
            'full' => '100%',
            'screen' => '100vh',
            'svh' => '100svh',
            'lvh' => '100lvh',
            'dvh' => '100dvh',
            'min' => 'min-content',
            'max' => 'max-content',
            'fit' => 'fit-content',
            'px' => '1px',
            '0' => '0',
        ];
        if (isset($keywords[$token])) {
            $v = $keywords[$token];
            if (in_array($v, ['auto', 'min-content', 'max-content', 'fit-content', '0'], true)) {
                return $v;
            }
            return $negative ? "-$v" : $v;
        }
        if (isset($this->spacing[$token])) {
            $v = $this->spacing[$token];
            return $negative ? "calc($v * -1)" : $v;
        }
        if (is_numeric($token)) {
            $rem = ((float) $token) * 0.25;
            return ($negative ? '-' : '') . $rem . 'rem';
        }
        return null;
    }

    private function resolveColor(string $token): ?string
    {
        $arb = $this->arbitrary($token);
        if ($arb !== null) return $arb;

        if (str_contains($token, '/')) {
            [$name, $alpha] = explode('/', $token, 2);
            $base = $this->colors[$name] ?? null;
            if ($base !== null && is_numeric($alpha)) {
                return "color-mix(in srgb, $base " . (int) $alpha . "%, transparent)";
            }
            return null;
        }

        return $this->colors[$token] ?? null;
    }

    private function resolveRadius(string $token): ?string
    {
        $arb = $this->arbitrary($token);
        if ($arb !== null) return $arb;
        if (isset($this->radii[$token])) return $this->radii[$token];

        $defaults = [
            'none' => '0',
            'sm' => '0.125rem',
            'md' => '0.375rem',
            'lg' => '0.5rem',
            'xl' => '0.75rem',
            '2xl' => '1rem',
            '3xl' => '1.5rem',
            'full' => '9999px',
        ];
        return $defaults[$token] ?? null;
    }

    private function resolveArbitraryOrNumber(string $token): ?string
    {
        $arb = $this->arbitrary($token);
        if ($arb !== null) return $arb;
        if (is_numeric($token)) return $token;
        return null;
    }

    /**
     * Returns the inside of [...] (with `_` → space) or null.
     */
    private function arbitrary(string $token): ?string
    {
        if (preg_match('/^\[(.+)\]$/', $token, $m)) {
            return str_replace('_', ' ', $m[1]);
        }
        return null;
    }

    private function negate(string $value): string
    {
        if ($value === '0' || $value === 'auto') return $value;
        if (preg_match('/^-?[\d.]+([a-z%]+)?$/i', $value)) {
            return str_starts_with($value, '-') ? substr($value, 1) : "-$value";
        }
        return "calc($value * -1)";
    }

    private function normaliseMap(array $map): array
    {
        $out = [];
        foreach ($map as $k => $v) {
            $out[(string) $k] = (string) $v;
        }
        return $out;
    }
}
